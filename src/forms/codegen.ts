import type { ResolvedTarget } from "../core/plugins.js";
import type { LocalizedText } from "../plugin-api/types.js";
import { luaQuote } from "../graph/codegen.js";
import { FormModel, isRegion, type Color, type FormDoc, type FormWidget } from "./model.js";

// ===== [S1] Typen · types =====

export interface FormWarning {
  widget?: string;
  code: "FORM_UNKNOWN_KIND" | "FORM_BACKDROP_TEMPLATE" | "FORM_SCRIPT_UNKNOWN" | "FORM_SCRIPT_SYNTAX" | "FORM_UNNAMED_ANCHOR" | "FORM_NAME_NEEDED";
  message: LocalizedText;
}

export interface FormGenResult {
  code: string;
  warnings: FormWarning[];
}

// ===== [S2] Skript-Argumente · script args =====

export const SCRIPT_PARAMS: Record<string, string> = {
  OnClick: "self, button, down",
  OnEvent: "self, event, ...",
  OnUpdate: "self, elapsed",
  OnEnter: "self, motion",
  OnLeave: "self, motion",
  OnShow: "self",
  OnHide: "self",
  OnMouseDown: "self, button",
  OnMouseUp: "self, button",
  OnEnterPressed: "self",
  OnEscapePressed: "self",
  OnTextChanged: "self, userInput",
  OnValueChanged: "self, value",
  OnCooldownDone: "self",
};

export function scriptSignature(script: string, target: ResolvedTarget): string {
  return target.scriptArgs === "arguments" ? SCRIPT_PARAMS[script] ?? "self, ..." : "";
}

// ===== [S4] orderForCreation =====

export function orderForCreation(model: FormModel): FormWidget[] {
  const out: FormWidget[] = [];
  const state = new Map<string, 1 | 2>();
  const visit = (w: FormWidget): void => {
    if (state.get(w.id) === 2) return;
    if (state.get(w.id) === 1) return; // cycle: model prevents it, stay safe
    state.set(w.id, 1);
    if (w.parent) visit(model.get(w.parent)!);
    for (const a of w.anchors) if (a.relativeTo) visit(model.get(a.relativeTo)!);
    state.set(w.id, 2);
    out.push(w);
  };
  model.doc.widgets.forEach(visit);
  return out;
}

// ===== [S3] generateFormLua =====

const col = (c: Color): string => `${c.r}, ${c.g}, ${c.b}, ${c.a}`;

export function generateFormLua(source: FormModel | FormDoc, target: ResolvedTarget): FormGenResult {
  const model = source instanceof FormModel ? source : new FormModel(source);
  const warnings: FormWarning[] = [];
  const lines: string[] = ["-- Generated by Freewood LUA IDE (forms editor) / Erzeugt vom Forms-Editor der Freewood LUA IDE", `-- Target / Ziel: ${target.id}`, ""];
  const frameMethods = new Set(target.widgets.get("Frame")?.methods ?? []);
  const texMethods = new Set(target.widgets.get("Texture")?.methods ?? []);
  const hasSetSize = frameMethods.has("SetSize");
  const backdropNeedsTemplate = !frameMethods.has("SetBackdrop") && target.scriptArgs === "arguments";
  const varOf = new Map<string, string>();
  const used = new Set<string>(["UIParent", "self", "this"]);
  const counters = new Map<string, number>();
  const nameFor = (w: FormWidget): string => {
    const base = w.name || `${w.kind.toLowerCase()}${(counters.set(w.kind, (counters.get(w.kind) ?? 0) + 1), counters.get(w.kind))}`;
    let v = base;
    let i = 2;
    while (used.has(v)) v = `${base}_${i++}`;
    used.add(v);
    return v;
  };

  const order = orderForCreation(model);
  for (const w of order) varOf.set(w.id, nameFor(w));
  const ref = (id: string | null, fallback: string): string => (id ? varOf.get(id) ?? fallback : fallback);

  for (const w of order) {
    const v = varOf.get(w.id)!;
    const def = target.widgets.get(w.kind);
    if (!def) warnings.push({ widget: w.id, code: "FORM_UNKNOWN_KIND", message: { en: `Widget type '${w.kind}' does not exist in target '${target.id}'.`, de: `Widget-Typ '${w.kind}' gibt es im Ziel '${target.id}' nicht.` } });
    const parent = w.parent ? ref(w.parent, "UIParent") : "UIParent";
    const nameArg = w.name ? luaQuote(w.name) : "nil";
    lines.push(`-- ${w.name || w.kind} (${w.id})`);
    if (isRegion(w.kind)) {
      const layer = luaQuote(w.layer ?? "ARTWORK");
      if (w.kind === "FontString") {
        const obj = w.font?.object ? `, ${luaQuote(w.font.object)}` : w.inherits ? `, ${luaQuote(w.inherits)}` : "";
        lines.push(`local ${v} = ${parent}:CreateFontString(${nameArg}, ${layer}${obj})`);
      } else {
        lines.push(`local ${v} = ${parent}:CreateTexture(${nameArg}, ${layer})`);
      }
    } else {
      const needTemplate = w.backdrop && backdropNeedsTemplate;
      const tpl = [w.inherits, needTemplate ? "BackdropTemplate" : undefined].filter(Boolean).join(",");
      if (needTemplate) warnings.push({ widget: w.id, code: "FORM_BACKDROP_TEMPLATE", message: { en: "Retail needs the BackdropTemplate for SetBackdrop; it was added.", de: "Retail braucht für SetBackdrop das BackdropTemplate; es wurde ergänzt." } });
      lines.push(`local ${v} = CreateFrame(${luaQuote(w.kind)}, ${nameArg}, ${parent}${tpl ? `, ${luaQuote(tpl)}` : ""})`);
    }
    if (w.width !== undefined && w.height !== undefined && hasSetSize && !isRegion(w.kind)) lines.push(`${v}:SetSize(${w.width}, ${w.height})`);
    else {
      if (w.width !== undefined) lines.push(`${v}:SetWidth(${w.width})`);
      if (w.height !== undefined) lines.push(`${v}:SetHeight(${w.height})`);
    }
    w.anchors.forEach((a) => {
      const rel = ref(a.relativeTo, a.relativeTo === null && w.parent ? parent : "UIParent");
      const relArg = a.relativeTo === null && !w.parent ? "UIParent" : rel;
      lines.push(`${v}:SetPoint(${luaQuote(a.point)}, ${relArg}, ${luaQuote(a.relativePoint)}, ${a.x}, ${a.y})`);
    });
    if (!isRegion(w.kind)) {
      if (w.strata) lines.push(`${v}:SetFrameStrata(${luaQuote(w.strata)})`);
      if (w.level) lines.push(`${v}:SetFrameLevel(${w.parent ? `${parent}:GetFrameLevel() + ` : ""}${w.level})`);
      if (w.movable) lines.push(`${v}:SetMovable(true)`);
      if (w.enableMouse) lines.push(`${v}:EnableMouse(true)`);
      if (w.alpha !== undefined && w.alpha !== 1) lines.push(`${v}:SetAlpha(${w.alpha})`);
      if (w.backdrop) {
        const b = w.backdrop;
        const parts: string[] = [];
        if (b.bgFile) parts.push(`bgFile = ${luaQuote(b.bgFile)}`);
        if (b.edgeFile) parts.push(`edgeFile = ${luaQuote(b.edgeFile)}`);
        if (b.tile !== undefined) parts.push(`tile = ${b.tile}`);
        if (b.tileSize !== undefined) parts.push(`tileSize = ${b.tileSize}`);
        if (b.edgeSize !== undefined) parts.push(`edgeSize = ${b.edgeSize}`);
        if (b.insets) parts.push(`insets = { left = ${b.insets.left}, right = ${b.insets.right}, top = ${b.insets.top}, bottom = ${b.insets.bottom} }`);
        lines.push(`${v}:SetBackdrop({ ${parts.join(", ")} })`);
        if (b.color) lines.push(`${v}:SetBackdropColor(${col(b.color)})`);
        if (b.borderColor) lines.push(`${v}:SetBackdropBorderColor(${col(b.borderColor)})`);
      }
    }
    if (w.kind === "Texture") {
      if (w.texture) lines.push(`${v}:SetTexture(${luaQuote(w.texture)})`);
      else if (w.color) lines.push(texMethods.has("SetColorTexture") ? `${v}:SetColorTexture(${col(w.color)})` : `${v}:SetTexture(${col(w.color)})`);
      if (w.texture && w.color) lines.push(`${v}:SetVertexColor(${col(w.color)})`);
    }
    if (w.kind === "FontString" || w.text !== undefined) {
      if (w.font?.path && w.font.size) lines.push(`${v}:SetFont(${luaQuote(w.font.path)}, ${w.font.size}${w.font.flags ? `, ${luaQuote(w.font.flags)}` : ""})`);
      if (w.text !== undefined) lines.push(`${v}:SetText(${luaQuote(w.text)})`);
      if (w.color && w.kind === "FontString") lines.push(`${v}:SetTextColor(${w.color.r}, ${w.color.g}, ${w.color.b}, ${w.color.a})`);
    }
    if (w.hidden) lines.push(`${v}:Hide()`);
    for (const [script, body] of Object.entries(w.scripts)) {
      if (!body.trim()) continue;
      const allowed = new Set<string>();
      for (let d: typeof def | undefined = def; d; d = d.inherits ? target.widgets.get(d.inherits) : undefined) d.scripts.forEach((s) => allowed.add(s));
      if (def && !allowed.has(script)) warnings.push({ widget: w.id, code: "FORM_SCRIPT_UNKNOWN", message: { en: `Script '${script}' is not known for ${w.kind} in target '${target.id}'.`, de: `Skript '${script}' ist für ${w.kind} im Ziel '${target.id}' nicht bekannt.` } });
      lines.push(`${v}:SetScript(${luaQuote(script)}, function(${scriptSignature(script, target)})`);
      for (const l of body.split("\n")) lines.push(`  ${l}`);
      lines.push("end)");
    }
    lines.push("");
  }
  return { code: lines.join("\n"), warnings };
}
